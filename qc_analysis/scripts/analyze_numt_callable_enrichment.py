#!/usr/bin/env python3
"""Callable-normalized enrichment of NUMT overlap for source mtDNA SNVs.

Compares observed fraction of variants in sample-specific NUMT intervals to the
fraction of depth-callable mtDNA bases within those intervals in THE SAME sample.
Before/after are within final sample-QC PASS subset; stage AFTER is final PASS.
No variant calling or other pipeline reruns.

Reads per-sample coverage generated by collect_variant_calling_results.py and
per-variant stage table from analyze_numt_variant_overlap.py. It explicitly
refuses to interpret missing depth or missing NUMT files as zero background.
"""
from __future__ import annotations
import argparse
import csv
import math
import sys
from collections import defaultdict
from pathlib import Path
from statistics import median

ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT))
from qc_analysis.lib.numt_annotation import load_sample_numts
from qc_analysis.scripts.run_local_heteroplasmy_qc import patterns, choose_numt_dir, read_metadata
from qc_analysis.lib.simple_yaml import read_simple_yaml

COHORTS={
 "hom10":("config/qc_cohort_hom10_mean_mtcn.yaml","results/qc_cohort_hom10_mean_mtcn",50),
 "homhet40":("config/qc_cohort_homhet40_mean_mtcn.yaml","results/qc_cohort_homhet40_mean_mtcn",100),
}

def resolve(p):
 p=Path(p).expanduser()
 return p if p.is_absolute() else ROOT/p

def read_rows(p):
 with p.open(newline="",encoding="utf8") as f:
  yield from csv.DictReader(f,delimiter="\t")

def write(p,fields,rows):
 p.parent.mkdir(parents=True,exist_ok=True)
 with p.open("w",newline="",encoding="utf8") as f:
  w=csv.DictWriter(f,fieldnames=fields,delimiter="\t",extrasaction="ignore")
  w.writeheader();w.writerows(rows)

def locate(folder,pats,s):
 for pat in pats:
  p=folder/pat.format(sample=s)
  if p.is_file():return p
 return None

def interval_bitset(intervals,length):
 bits=bytearray(length+1)
 for a,b in intervals:
  a,b=sorted((int(a),int(b)))
  if a<1 or b>length: raise ValueError(f"NUMT interval {a}-{b} outside mtDNA length {length}")
  bits[a:b+1]=b"\x01"*(b-a+1)
 return bits

def fai_length(folder,reference,species):
 candidates=[folder/(name+".fa.fai") for name in dict.fromkeys((reference,species))]
 p=next((p for p in candidates if p.is_file()),None)
 if not p:raise FileNotFoundError(f"Missing mtDNA FAI for species/reference {species}/{reference}; tried {candidates}")
 lines=[x.rstrip("\n").split("\t") for x in p.read_text().splitlines() if x.strip()]
 chrmt=[int(x[1]) for x in lines if x[0] in ("chrM","MT")]
 if len(chrmt)==1:return chrmt[0]
 if len(lines)==1:return int(lines[0][1])
 raise ValueError(f"Ambiguous mtDNA length in {p}")

def callable_bits(path,length,min_dp):
 # Depths are per-position merged MAX: repeated target/chrom entries count once
 # and are callable if ANY chrM row is >= depth threshold.
 if not path.is_file():return None
 bits=bytearray(length+1)
 with path.open(newline="",encoding="utf8") as f:
  reader=csv.DictReader(f,delimiter="\t")
  if not {"chrom","pos","target","coverage"}.issubset(reader.fieldnames or []):
   raise ValueError(f"Unexpected coverage columns {path}: {reader.fieldnames}")
  for r in reader:
   if r["chrom"] not in ("chrM","MT") and r["target"] not in ("chrM","MT"):
    continue
   try:p=int(r["pos"]); dp=float(r["coverage"])
   except (ValueError,TypeError):continue
   if 1<=p<=length and math.isfinite(dp) and dp>=min_dp:bits[p]=1
 return bits

def main():
 ap=argparse.ArgumentParser()
 ap.add_argument("--cohort",choices=("both","hom10","homhet40"),default="both")
 ap.add_argument("--ref-chrm-dir",type=Path,default=ROOT/"references/variant_calling/Ref_chrM")
 ap.add_argument("--besthit-dir",type=Path)
 ap.add_argument("--highconf-dir",type=Path)
 ap.add_argument("--variant-dir",type=Path,default=ROOT/"results/numt_overlap_before_after")
 ap.add_argument("--output",type=Path,default=ROOT/"results/numt_callable_enrichment")
 ap.add_argument("--min-dp-hom10",type=int,default=50)
 ap.add_argument("--min-dp-homhet40",type=int,default=100)
 args=ap.parse_args()
 out=resolve(args.output)
 per_sample=[];diagnostics=[]
 selected=COHORTS if args.cohort=="both" else (args.cohort,)
 for cohort in selected:
  config_path,cohort_root,default_dp=COHORTS[cohort]
  cfg=read_simple_yaml(resolve(config_path))
  sec=cfg.get("local_heteroplasmy_qc") or {}
  root=resolve(cohort_root)
  variants=resolve(args.variant_dir)/(cohort+"_numt_overlap_per_variant.tsv")
  if not variants.is_file():raise FileNotFoundError(variants)
  metadata_path=resolve(sec.get("sample_ref_file","config/sample_ref_file.tsv"))
  species_map,ref_map=read_metadata(metadata_path)
  samps=sorted({r["sample"] for r in read_rows(variants)})
  best_pats=patterns(sec.get("numt_besthit_pattern"),[
   "{sample}.numt_vs_chrM.besthit.tsv","{sample}.numt_besthit.tsv",
   "{sample}.besthit.tsv","{sample}.tsv"])
  high_pats=patterns(sec.get("numt_highconf_pattern"),["{sample}.highconf_numt.bed"])
  fallback=ROOT/"data/numt_besthit"
  best_dir=resolve(args.besthit_dir) if args.besthit_dir else choose_numt_dir(
   sec.get("numt_besthit_dir"),best_pats,samps,[fallback])
  high_dir=resolve(args.highconf_dir) if args.highconf_dir else choose_numt_dir(
   sec.get("numt_highconf_dir"),high_pats,samps,[best_dir,fallback])
  mindp=args.min_dp_hom10 if cohort=="hom10" else args.min_dp_homhet40
  covdir=root/"collected_variant_calling_results/collected_cov"
  if not covdir.is_dir():raise FileNotFoundError(covdir)
  sample_data={}; groups=defaultdict(lambda:[0,0,0])
  for sample in samps:
   sp=species_map.get(sample);ref=ref_map.get(sample)
   if not sp or not ref:
    diagnostics.append((cohort,sample,"missing_metadata"));continue
   length=fai_length(resolve(args.ref_chrm_dir),ref,sp)
   bh=locate(best_dir,best_pats,sample)
   hc=locate(high_dir,high_pats,sample)
   if bh is None or hc is None:
    diagnostics.append((cohort,sample,"missing_besthit_or_highconf"));continue
   cov=callable_bits(covdir/(sample+".merged.max_depth.per_base_coverage.tsv"),length,mindp)
   if cov is None:
    diagnostics.append((cohort,sample,"missing_coverage"));continue
   iv=load_sample_numts(sample,sp,ref,bh,hc)
   high=interval_bitset([(x.chrm_start,x.chrm_end) for x in iv
                         if x.tier=="HIGH_CONF_NUMT"],length)
   anyb=interval_bitset([(x.chrm_start,x.chrm_end) for x in iv],length)
   ncall=sum(cov)
   if ncall==0:
    diagnostics.append((cohort,sample,"no_callable_positions"));continue
   expect={}
   for tier,bits in (("high",high),("any",anyb)):
    numtcall=sum(a & b for a,b in zip(cov,bits))
    expect[tier]=(numtcall,ncall,numtcall/ncall,bits)
   sample_data[sample]=(sp,ref,length,cov,expect)
  for r in read_rows(variants):
   sample=r["sample"]
   if sample not in sample_data:continue
   try:pos=int(r["source_pos"])
   except (TypeError,ValueError):continue
   sp,ref,length,cov,expect=sample_data[sample]
   if not 1<=pos<=length or not cov[pos]:
    continue
   cls=r["call_class"]
   if cls not in ("HOM","HET"):continue
   for stage in (("BEFORE","AFTER") if r["final_status"]=="PASS" else ("BEFORE",)):
    for tier in ("high","any"):
     bits=expect[tier][3]
     g=groups[(sample,cls,stage,tier)]
     g[0]+=1
     g[1]+=bits[pos]
  for (sample,cls,stage,tier),(n,hit,_) in sorted(groups.items()):
   sp,ref,length,cov,expected=sample_data[sample]
   callable_numt,callable_all,bg,bits=expected[tier]
   if n<1 or bg<=0 or bg>=1:
    diagnostics.append((cohort,sample,"background_0_or_1_"+tier))
    continue
   obs=hit/n
   per_sample.append(dict(cohort=cohort,sample=sample,species=sp,reference_key=ref,
    variant_class=cls,stage=stage,tier=tier,min_depth=mindp,
    callable_bp=callable_all,callable_numt_bp=callable_numt,
    expected_numt_pct=round(100*bg,5),n_callable_variants=n,
    n_variant_numt_hits=hit,observed_numt_pct=round(100*obs,5),
    enrichment_ratio=round(obs/bg,6),enrichment_difference_pp=round(100*(obs-bg),5)))
  print(cohort,"variant samples",len(samps),"assessable background samples",len(sample_data),
        "per-sample summary rows",sum(r["cohort"]==cohort for r in per_sample))
  if not sample_data:raise RuntimeError(f"No callable/NUMT matched samples for {cohort}")
 fields=["cohort","sample","species","reference_key","variant_class","stage","tier","min_depth",
         "callable_bp","callable_numt_bp","expected_numt_pct",
         "n_callable_variants","n_variant_numt_hits","observed_numt_pct",
         "enrichment_ratio","enrichment_difference_pp"]
 write(out/"numt_callable_enrichment_per_sample.tsv",fields,per_sample)
 write(out/"numt_callable_enrichment_diagnostics.tsv",["cohort","sample","reason"],
       [dict(zip(["cohort","sample","reason"],x)) for x in diagnostics])
 summary=[]
 for cohort in selected:
  for cls in ("HOM","HET"):
   for stage in ("BEFORE","AFTER"):
    for tier in ("high","any"):
     dat=[r for r in per_sample if (r["cohort"],r["variant_class"],r["stage"],r["tier"])==(cohort,cls,stage,tier)]
     if not dat:continue
     # Matched sample median, not pooled variant-weighted statistic.
     ratios=sorted(r["enrichment_ratio"] for r in dat)
     diffs=sorted(r["enrichment_difference_pp"] for r in dat)
     observed=sum(r["n_variant_numt_hits"] for r in dat)
     total=sum(r["n_callable_variants"] for r in dat)
     expected=sum(r["expected_numt_pct"]*r["n_callable_variants"]/100 for r in dat)
     summary.append(dict(cohort=cohort,variant_class=cls,stage=stage,tier=tier,
       n_samples=len(dat),n_callable_variants=total,pooled_observed_pct=round(100*observed/total,4),
       variant_weighted_expected_pct=round(100*expected/total,4),
       median_sample_enrichment_ratio=round(median(ratios),4),
       median_sample_difference_pp=round(median(diffs),4)))
 fields=["cohort","variant_class","stage","tier","n_samples","n_callable_variants",
         "pooled_observed_pct","variant_weighted_expected_pct",
         "median_sample_enrichment_ratio","median_sample_difference_pp"]
 write(out/"numt_callable_enrichment_summary.tsv",fields,summary)
 for r in summary:
  if r["tier"]=="high":
   print("{cohort} {variant_class} {stage} n={n_samples} observed={pooled_observed_pct}% "
         "expected={variant_weighted_expected_pct}% median sample enrichment="
         "{median_sample_enrichment_ratio}".format(**r))
 print("Saved to",out)
 print("CAUTION: the analysis uses depth-defined callable positions; it does not assert "
       "base-level allele-specific sensitivity. For high-conf calls this uses source "
       "positions and sample-specific intervals, not the species union.")

if __name__=="__main__":main()
